     * Сначала ищем правило по первому слову названия (обычно это и есть продукт: «Тефтели в соусе» — тефтели),
     * потом по началу любого слова («Картофельное пюре» — пюре). Совпадение только с начала слова:
     * «рис» не ловит «барбарис», «мёд» не ловит «медовик».
     */
    fun forName(name: String): List<Portion> {
        val n = " " + FoodBase.norm(name) + " "
        fun key(k: String) = " " + FoodBase.norm(k)
        fun ok(k: String) = !(k == "мёд" && n.contains(" медов"))
        return (rules.firstOrNull { (keys, _) -> keys.any { k -> n.startsWith(key(k)) && ok(k) } }
            ?: rules.firstOrNull { (keys, _) -> keys.any { k -> n.contains(key(k)) && ok(k) } })
            ?.second.orEmpty()
    }
